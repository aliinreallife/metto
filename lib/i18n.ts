export function persianDigits(input: string | number, lang: Lang): string {
  const s = String(input);
  if (lang !== "fa") return s;
  const map = "۰۱۲۳۴۵۶۷۸۹";
  return s.replace(/\d/g, (d) => map[Number(d)]);
}
